import { describe, expect, it } from "vitest";
import { STANCES, USES, apa, chicago, disclosure, mla, parts, syllabusStatement, verdictFor, type Citation } from "../aiUse";

const cite: Citation = { tool: "ChatGPT", company: "OpenAI", date: "2025-08-21", title: "High school grammar concepts", prompt: "Explain antibiotics to a first-year student in plain words", url: "https://chatgpt.com/share/abc", version: "GPT-5" };

describe("citations", () => {
  it("reads dates without time zones", () => {
    expect(parts("2025-08-21")).toEqual({ y: 2025, m: 8, d: 21 });
    expect(parts("2025-13-01")).toBeNull();
    expect(parts("")).toBeNull();
  });

  it("builds APA's 2025 format: company, date, italic-style title, [Generative AI chat], tool, link", () => {
    const a = apa(cite);
    expect(a.reference).toBe("OpenAI. (2025, August 21). High school grammar concepts [Generative AI chat]. ChatGPT. https://chatgpt.com/share/abc");
    expect(a.reference).not.toContain("Large language model");
    expect(a.inText).toBe("(OpenAI, 2025)");
  });

  it("builds MLA with the prompt as the title and no author", () => {
    const m = mla(cite);
    expect(m.entry).toBe("“Explain antibiotics to a first-year student in plain words” prompt. ChatGPT, GPT-5, OpenAI, 21 Aug. 2025, chatgpt.com/share/abc.");
    expect(m.inText).toBe("(“Explain antibiotics to a…”)");
    expect(mla({ ...cite, version: "", url: "" }).entry).toBe("“Explain antibiotics to a first-year student in plain words” prompt. ChatGPT, OpenAI, 21 Aug. 2025.");
  });

  it("builds a Chicago footnote, with the prompt only when asked and shortened when long", () => {
    expect(chicago(cite, false)).toBe("Text generated by ChatGPT, OpenAI, August 21, 2025, https://chatgpt.com/share/abc.");
    expect(chicago(cite, true)).toContain("Prompt: “Explain antibiotics");
    expect(chicago({ ...cite, prompt: "x".repeat(200) }, true)).toContain(`${"x".repeat(160)}…”`);
  });

  it("leaves visible placeholders for what's missing", () => {
    const blank: Citation = { tool: "", company: "", date: "", title: "", prompt: "", url: "", version: "" };
    expect(apa(blank).reference).toContain("[AI company]");
    expect(mla(blank).entry).toContain("[Prompt]");
    expect(chicago(blank, false)).toContain("[Month day, year]");
  });
});

describe("disclosure", () => {
  it("writes a short statement the student can edit", () => {
    const t = disclosure({ tool: "Claude", company: "Anthropic", date: "2026-11-07", purposes: ["brainstorm ideas", "proofread my writing"], changed: "I rewrote the outline in my own words" });
    expect(t).toBe("I used Claude (Anthropic) on November 7, 2026 to brainstorm ideas and proofread my writing. I rewrote the outline in my own words. The final work, and any mistakes in it, are my own.");
    expect(disclosure({ tool: "", company: "", date: "", purposes: [], changed: "" })).toContain("[AI tool]");
  });
});

describe("can I use AI for this", () => {
  const use = (id: string) => USES.find((u) => u.id === id)!;

  it("says no to everything when the instructor says no AI", () => {
    for (const u of USES) expect(verdictFor(u, "none").verdict, u.id).toBe("no");
  });

  it("never calls handing in AI's work fine without clear permission", () => {
    expect(verdictFor(use("draft"), "unknown").verdict).toBe("no");
    expect(verdictFor(use("draft"), "limited").verdict).toBe("no");
    expect(verdictFor(use("draft"), "disclose").verdict).toBe("check");
    expect(verdictFor(use("draft"), "open").verdict).not.toBe("no");
  });

  it("treats studying as fine, but still tells someone who hasn't checked to check", () => {
    expect(verdictFor(use("explain"), "unknown").verdict).toBe("fine");
    expect(verdictFor(use("explain"), "unknown").why).toMatch(/check/i);
  });

  it("asks for a check on in-between uses when the rules are unknown or limited", () => {
    expect(verdictFor(use("feedback"), "unknown").verdict).toBe("check");
    expect(verdictFor(use("code"), "limited").verdict).toBe("check");
    expect(verdictFor(use("feedback"), "disclose").verdict).toBe("fine");
  });

  it("keeps quizzes and exams as something to confirm even when AI is allowed", () => {
    expect(verdictFor(use("graded"), "open").verdict).toBe("check");
    expect(STANCES).toHaveLength(5);
  });
});

describe("the syllabus statement", () => {
  it("writes each stance in plain words and always invites questions", () => {
    for (const stance of ["none", "limited", "disclose", "open"] as const) {
      const t = syllabusStatement({ stance, uses: [], disclose: false, extra: "" });
      expect(t).toMatch(/^Generative AI in this course/);
      expect(t).toMatch(/ask me/);
    }
  });

  it("lists the uses a limited policy allows and asks for disclosure when chosen", () => {
    const t = syllabusStatement({ stance: "limited", uses: ["brainstorming ideas and outlines", "proofreading and grammar checks"], disclose: true, extra: "Exams are closed to AI." });
    expect(t).toContain("for brainstorming ideas and outlines and proofreading and grammar checks");
    expect(t).toContain("which tool you used");
    expect(t).toContain("Exams are closed to AI.");
    expect(syllabusStatement({ stance: "disclose", uses: [], disclose: false, extra: "" })).toContain("which tool you used");
    expect(syllabusStatement({ stance: "none", uses: [], disclose: true, extra: "" })).toContain("which tool you used");
  });
});
