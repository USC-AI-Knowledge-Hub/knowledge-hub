/**
 * Writes firebase/firestore.rules (the AI Team board's security rules) and src/lib/board/blocked-words.json
 * (the same block list, so the form can say why before sending). Run `npm run firebase-rules` after
 * changing the rules below or the word list; a test fails if the committed files are out of date.
 *
 * The rules are the board's only guard: there is no server. Every visitor signs in anonymously, so
 * request.auth.uid identifies a browser, and the rules check every write the way supabase/schema.sql's
 * functions did: names and lengths, links, the block list, one reaction per person, three reports hide a
 * post, edits and deletes by the author only, and a pause between posts.
 */
import { writeFileSync } from "node:fs";
import { cuss } from "cuss";

/** The starter list: the cuss package's "very likely profanity" entries (MIT). */
export const BLOCKED: string[] = [
  ...new Set(
    Object.entries(cuss)
      .filter(([, sureness]) => sureness === 2)
      .map(([w]) => w.toLowerCase().trim())
      .filter((w) => w.length >= 2 && /^[a-z0-9' -]+$/.test(w)),
  ),
].sort();

/**
 * How the block list is checked, here and on the page (src/lib/board/firebaseStore.ts does the same):
 * lower case, look-alikes swapped back (0 for o, @ for a ...), then the text is split into words.
 * The list is a few patterns of plain words: a list literal counts each word against the rules' limit of
 * 1,000 expressions, and one pattern for every word was too big for the rules engine.
 */
export const LOOK_ALIKES: [string, string][] = [["[0]", "o"], ["[1]", "i"], ["[3]", "e"], ["[4@]", "a"], ["[5$]", "s"], ["[7]", "t"]];
const tokens = (w: string) => w.split(/[^a-z0-9]+/).filter(Boolean);
export const SINGLE = (words = BLOCKED) => [...new Set(words.filter((w) => tokens(w).length === 1).map((w) => tokens(w)[0]))].sort();
export const PHRASES = (words = BLOCKED) => [...new Set(words.filter((w) => tokens(w).length > 1).map((w) => tokens(w).join(" ")))].sort();
/** Every entry as whole words, on text already lowered and with look-alikes swapped: one pattern, one rules expression. */
export const blockRegex = (words = BLOCKED) =>
  `(?s).*(^|[^a-z0-9])(${[...SINGLE(words), ...PHRASES(words)].map((p) => p.replace(/ /g, "[^a-z0-9]+")).join("|")})([^a-z0-9]|$).*`;

/** The pattern in parts of up to 300 entries: Firestore's rules engine fails on one pattern for the whole list. */
export const blockChunks = (words = BLOCKED, size = 300) => {
  const all = [...SINGLE(words), ...PHRASES(words)];
  const out: string[] = [];
  for (let i = 0; i < all.length; i += size) out.push(`(?s).*(^|[^a-z0-9])(${all.slice(i, i + size).map((p) => p.replace(/ /g, "[^a-z0-9]+")).join("|")})([^a-z0-9]|$).*`);
  return out;
};

/** Whole phrases, on text already lowered and with look-alikes swapped. Used with string.matches(). */
export const phraseRegex = (words = BLOCKED) => `(?s).*(^|[^a-z0-9])(${PHRASES(words).map((p) => p.replace(/ /g, "[^a-z0-9]+")).join("|")})([^a-z0-9]|$).*`;

/** Reaction ids as stored; the page shows them as emoji. */
export const REACTION_IDS = ["up", "love", "idea", "party", "think"] as const;

/** Seconds a browser waits between posts. */
export const POST_GAP_SECONDS = 15;

export function rules(words = BLOCKED): string {
  const reactionChecks = REACTION_IDS.map((k) => `reactionChange(postId, "${k}")`).join(" || ");
  return `rules_version = '2';
// AI Team board. Generated by scripts/gen-firebase-rules.ts: edit that file, then run npm run firebase-rules.
// Paste this whole file into Firebase console > Firestore Database > Rules, then Publish.
service cloud.firestore {
  match /databases/{db}/documents {
    function signedIn() { return request.auth != null; }
    function me() { return request.auth.uid; }
    function changed() { return request.resource.data.diff(resource.data).affectedKeys(); }
    function post(id) { return /databases/$(db)/documents/posts/$(id); }
    function reactionDoc(id, k) { return /databases/$(db)/documents/reactions/$(id + "_" + me() + "_" + k); }
    function reportDoc(id) { return /databases/$(db)/documents/reports/$(id + "_" + me()); }
    function userDoc() { return /databases/$(db)/documents/users/$(me()); }

    function plain(t) { return t.lower()${LOOK_ALIKES.map(([re, to]) => `.replace("${re}", "${to}")`).join("")}; }
${blockChunks(words).map((r, i) => `    function blocked${i}(t) { return t.matches("${r}"); }`).join("\n")}
    function blocked(t) { return ${blockChunks(words).map((_, i) => `blocked${i}(plain(t))`).join(" || ")}; }
    function links(t) { return t.matches("(?is).*(https?://|www[.]).*"); }
    function tooManyLinks(t) { return t.matches("(?is).*(https?://|www[.]).*(https?://|www[.]).*(https?://|www[.]).*"); }
    function okName(n) { return n is string && n.size() >= 1 && n.size() <= 40 && n.trim() == n && !links(n) && !blocked(n); }
    function okBody(b) { return b is string && b.size() >= 1 && b.size() <= 2000 && !tooManyLinks(b) && !blocked(b); }
    function okId(s) { return s is string && s.matches("[a-z0-9-]{1,40}"); }

    // A browser may post again ${POST_GAP_SECONDS} seconds after its last post. Each post stamps users/{uid} in the same write.
    function pausedLongEnough() {
      return !exists(userDoc()) || get(userDoc()).data.lastPost < request.time - duration.value(${POST_GAP_SECONDS}, "s");
    }

    // A reply hangs from a live top-level post on the same board and topic.
    function okParent(d) {
      return d.parentId == null || (
        d.parentId is string && exists(post(d.parentId)) &&
        get(post(d.parentId)).data.parentId == null &&
        !get(post(d.parentId)).data.deleted && !get(post(d.parentId)).data.hidden &&
        get(post(d.parentId)).data.board == d.board && get(post(d.parentId)).data.topic == d.topic
      );
    }

    // One reaction of a kind per browser: the count moves by one as this browser's reaction doc appears or goes.
    function reactionChange(postId, k) {
      let before = resource.data.reactions.get(k, 0);
      let after = request.resource.data.reactions.get(k, 0);
      return request.resource.data.reactions.diff(resource.data.reactions).affectedKeys().hasOnly([k]) && (
        (after == before + 1 && !exists(reactionDoc(postId, k)) && existsAfter(reactionDoc(postId, k))) ||
        (after == before - 1 && exists(reactionDoc(postId, k)) && !existsAfter(reactionDoc(postId, k)))
      );
    }

    match /posts/{postId} {
      // Hidden posts are left out, so a list must ask for hidden == false.
      allow read: if resource.data.hidden == false;

      allow create: if signedIn()
        && request.resource.data.keys().hasOnly(["board", "topic", "parentId", "name", "body", "uid", "createdAt", "editedAt", "deleted", "hidden", "reactions", "reports"])
        && request.resource.data.keys().hasAll(["board", "topic", "parentId", "name", "body", "uid", "createdAt", "editedAt", "deleted", "hidden", "reactions", "reports"])
        && request.resource.data.uid == me()
        && okId(request.resource.data.board) && okId(request.resource.data.topic)
        && okName(request.resource.data.name) && okBody(request.resource.data.body)
        && request.resource.data.createdAt == request.time && request.resource.data.editedAt == null
        && request.resource.data.deleted == false && request.resource.data.hidden == false
        && request.resource.data.reactions == {} && request.resource.data.reports == 0
        && okParent(request.resource.data)
        && pausedLongEnough() && getAfter(userDoc()).data.lastPost == request.time;

      allow update: if signedIn() && !resource.data.deleted && (
        // The author edits the text.
        (resource.data.uid == me() && changed().hasOnly(["body", "editedAt"]) && okBody(request.resource.data.body) && request.resource.data.editedAt == request.time) ||
        // The author deletes a post that has replies: it stays as an empty stub so the replies keep their place.
        (resource.data.uid == me() && changed().hasOnly(["deleted", "body"]) && request.resource.data.deleted == true && request.resource.data.body == "") ||
        // Anyone reacts, once per kind.
        (!resource.data.hidden && changed().hasOnly(["reactions"]) && (${reactionChecks})) ||
        // Anyone reports, once; the third report hides the post.
        (changed().hasOnly(["reports", "hidden"]) && request.resource.data.reports == resource.data.reports + 1
          && request.resource.data.hidden == (request.resource.data.reports >= 3)
          && !exists(reportDoc(postId)) && existsAfter(reportDoc(postId)))
      );

      // The author removes a post outright (the page does this only when nothing replies to it).
      allow delete: if signedIn() && resource.data.uid == me();
    }

    // Who reacted with what. Ids are {postId}_{uid}_{reaction}, so a browser can only hold one of each.
    match /reactions/{id} {
      // A browser checks whether it already reacted, so reading one of its own that doesn't exist is allowed.
      allow get: if signedIn() && (resource == null || resource.data.uid == me());
      allow create: if signedIn()
        && request.resource.data.keys().hasOnly(["postId", "uid", "k"]) && request.resource.data.uid == me()
        && id == request.resource.data.postId + "_" + me() + "_" + request.resource.data.k
        && request.resource.data.k in ${JSON.stringify(REACTION_IDS)}
        && getAfter(post(request.resource.data.postId)).data.reactions.get(request.resource.data.k, 0)
           == get(post(request.resource.data.postId)).data.reactions.get(request.resource.data.k, 0) + 1;
      allow delete: if signedIn() && resource.data.uid == me()
        && (!exists(post(resource.data.postId)) || getAfter(post(resource.data.postId)).data.reactions.get(resource.data.k, 0)
           == get(post(resource.data.postId)).data.reactions.get(resource.data.k, 0) - 1);
    }

    // Who reported what, so nobody reports twice. Editors read these in the console.
    match /reports/{id} {
      allow create: if signedIn()
        && request.resource.data.keys().hasOnly(["postId", "uid"]) && request.resource.data.uid == me()
        && id == request.resource.data.postId + "_" + me()
        && getAfter(post(request.resource.data.postId)).data.reports == get(post(request.resource.data.postId)).data.reports + 1;
    }

    // When each browser last posted, for the pause between posts.
    match /users/{uid} {
      allow get: if signedIn() && uid == me();
      allow create, update: if signedIn() && uid == me()
        && request.resource.data.keys().hasOnly(["lastPost"]) && request.resource.data.lastPost == request.time && pausedLongEnough();
    }
  }
}
`;
}

if (process.argv[1]?.endsWith("gen-firebase-rules.ts")) {
  writeFileSync(new URL("../firebase/firestore.rules", import.meta.url), rules());
  writeFileSync(new URL("../src/lib/board/blocked-words.json", import.meta.url), JSON.stringify({ single: SINGLE(), phrases: PHRASES() }) + "\n");
  console.log(`Wrote firebase/firestore.rules and the block list (${BLOCKED.length} words).`);
}
