import { expect, test } from "@playwright/test";

test.describe("using AI in coursework", () => {
  test.use({ viewport: { width: 1280, height: 900 } });

  test("says how risky each use is for the course's stance", async ({ page }) => {
    await page.goto("/ai-use");
    await expect(page.getByRole("heading", { level: 1 })).toHaveText("Using AI in your coursework");
    const graded = page.locator(".ai-use", { hasText: "Answer a quiz, exam or graded question" });
    await expect(graded.locator(".ai-verdict")).toHaveText(/Don't/);
    await page.getByRole("radiogroup", { name: /What does your course say/ }).getByRole("radio", { name: "AI is allowed" }).click();
    await expect(page.locator(".ai-use", { hasText: "Have a concept explained to me" }).locator(".ai-verdict")).toHaveText(/Usually fine/);
    await page.getByRole("radiogroup", { name: /What does your course say/ }).getByRole("radio", { name: "AI is not allowed" }).click();
    await expect(page.locator(".ai-use[data-verdict='no']")).toHaveCount(9);
  });

  test("builds a disclosure note and APA, MLA and Chicago citations", async ({ page }) => {
    await page.goto("/ai-use");
    await page.getByLabel("Date you used it").fill("2026-11-07");
    await page.getByLabel("What you changed or checked (optional)").fill("I rewrote the outline in my own words");
    await expect(page.getByLabel("Your disclosure note")).toHaveValue(/I used ChatGPT \(OpenAI\) on November 7, 2026 to brainstorm ideas\. I rewrote the outline in my own words\./);

    await page.getByLabel("Date of the chat").fill("2025-08-21");
    await page.getByLabel("Title of the chat (for APA)").fill("High school grammar concepts");
    await page.getByLabel("Your prompt (for MLA and Chicago)").fill("Explain antibiotics in plain words");
    await page.getByLabel("Link to the chat or the tool").fill("https://chatgpt.com/share/abc");
    await expect(page.getByLabel("APA reference list entry")).toHaveValue("OpenAI. (2025, August 21). High school grammar concepts [Generative AI chat]. ChatGPT. https://chatgpt.com/share/abc");
    await expect(page.getByLabel("APA in-text citation")).toHaveValue("(OpenAI, 2025)");
    await expect(page.getByLabel("MLA works cited entry")).toHaveValue("“Explain antibiotics in plain words” prompt. ChatGPT, OpenAI, 21 Aug. 2025, chatgpt.com/share/abc.");
    await expect(page.getByLabel("Chicago footnote")).toHaveValue("Text generated by ChatGPT, OpenAI, August 21, 2025, https://chatgpt.com/share/abc.");
    await page.getByLabel("Include my prompt in the note").check();
    await expect(page.getByLabel("Chicago footnote")).toHaveValue(/Prompt: “Explain antibiotics in plain words”/);
    await expect(page.getByRole("link", { name: "guide to citing generative AI" })).toHaveAttribute("href", /libguides\.usc\.edu/);
  });

  test("builds a syllabus statement for instructors", async ({ page }) => {
    await page.goto("/ai-use");
    const box = page.getByLabel("Draft syllabus statement");
    await expect(box).toHaveValue(/Generative AI in this course/);
    await expect(box).toHaveValue(/which tool you used/);
    await page.getByRole("radiogroup", { name: "Your stance" }).getByRole("radio", { name: "No AI on graded work" }).click();
    await expect(box).toHaveValue(/Please do not use generative AI tools/);
    await page.getByLabel("Anything to add (optional)").fill("Exams are closed to AI.");
    await expect(box).toHaveValue(/Exams are closed to AI\./);
  });

  test("is found by search words and linked from the footer", async ({ page }) => {
    await page.goto("/");
    await page.getByRole("link", { name: "Using AI in coursework" }).click();
    await expect(page).toHaveURL(/\/ai-use$/);
  });

  test("fits a phone without sideways scrolling", async ({ page }) => {
    await page.setViewportSize({ width: 360, height: 800 });
    await page.goto("/ai-use");
    await page.getByLabel("Your prompt (for MLA and Chicago)").fill("a very long prompt ".repeat(10));
    await page.getByLabel("Link to the chat or the tool").fill("https://example.com/" + "a".repeat(120));
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0);
  });
});
